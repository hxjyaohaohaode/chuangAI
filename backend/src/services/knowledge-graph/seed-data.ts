/**
 * 知识图谱基础种子数据 —— 小学古诗词候选集 20 首
 *
 * 设计原则：
 * 1. 原文一字不差（已逐字核对统编版教材用字，如"唯见"非"惟见"、"曈曈"非"瞳瞳"）
 * 2. 主题/意象/修辞标签由语文学科教学专家视角标注（非诗歌鉴赏专家视角），
 *    以服务小学课堂认知诊断为目标
 * 3. 意象标签用"文化意象"粒度（如"月"统一指代明月意象，不区分"残月/满月"）
 * 4. 修辞标签用小学阶段可理解的术语（拟人/比喻/对偶/夸张/借代/设问/反复/白描/哲理）
 *
 * 注意：历史方案曾使用“132 首必背”口径，该口径未获官方确认；当前按逐首溯源区分教材核心与拓展篇目。
 */

// ─────────────────────────────────────────────────────────────
// 类型定义
// ─────────────────────────────────────────────────────────────

/**
 * 种子古诗节点（含创作诗人、所属朝代等冗余字段，便于一次性建图）
 */
export interface SeedPoem {
    /** 历史兼容 ID，格式 tongbian-XXX；ID 前缀本身不代表已完成教材验收 */
    id: string
    title: string
    poet: string
    dynasty: string
    /** 诗词原文（一字不差，标点用全角） */
    content: string
    /** 关键字词注释（精炼至 1-2 句，便于小学教师授课） */
    annotation: Record<string, string>
    /** 主题标签（小学阶段可理解的粒度） */
    themes: string[]
    /** 意象标签（文化意象粒度） */
    images: string[]
    /** 修辞标签 */
    rhetoric: string[]
    /** 适用年级 */
    gradeLevel: string
    /** 难度 1-5（综合考量字词密度、修辞复杂度、思想深度） */
    difficulty: 1 | 2 | 3 | 4 | 5
}

/**
 * 种子诗人节点
 */
export interface SeedPoet {
    id: string
    name: string
    dynasty: string
    /** 生卒年（公元纪年，无可靠记录则留空） */
    birthYear?: number
    deathYear?: number
    /** 诗风简述 */
    style?: string
    /** 一句话简介 */
    brief?: string
}

/**
 * 种子朝代节点
 */
export interface SeedEra {
    name: string
    /** 起止年份（大致范围，便于同时代判定） */
    startYear?: number
    endYear?: number
}

/**
 * 诗人师承关系（"受影响者 → 被影响者"，即后者以前者为师法对象）
 */
export interface SeedMentorship {
    /** 师法对象（前人） */
    mentor: string
    /** 受影响者（后人） */
    mentee: string
    /** 师承关系说明 */
    note: string
}

